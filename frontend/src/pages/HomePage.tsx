import { useState } from "react";
import { useNavigate } from "react-router-dom";
import PredictionForm from "../components/PredictionForm";
import CornerMarks from "../components/CornerMarks";
import { predictPrice, ApiRequestError } from "../api/predictionClient";
import type { PredictionRequest } from "../types/prediction";

export default function HomePage() {
  const navigate = useNavigate();
  const [submitting, setSubmitting] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function handleSubmit(payload: PredictionRequest) {
    setSubmitting(true);
    setError(null);
    try {
      const result = await predictPrice(payload);
      navigate("/result", { state: { payload, result } });
    } catch (err) {
      const message =
        err instanceof ApiRequestError
          ? err.message
          : "Something went wrong while estimating this property. Please try again.";
      setError(message);
    } finally {
      setSubmitting(false);
    }
  }

  return (
    <div className="hero">
      <section className="hero-panel">
        <CornerMarks />
        <div className="hero-panel__inner">
          <span className="eyebrow">Survey No. 01 · Valuation Desk</span>
          <h1 className="hero-title">
            What's your
            <br />
            property worth?
          </h1>
          <p className="hero-copy">
            Enter a few details about the property and our valuation model —
            trained on real listings across India — will plot an instant
            market estimate.
          </p>
          <dl className="stat-strip">
            <div className="stat">
              <dt>Listings surveyed</dt>
              <dd>177,528</dd>
            </div>
            <div className="stat">
              <dt>Cities covered</dt>
              <dd>50</dd>
            </div>
            <div className="stat">
              <dt>Model fit (R²)</dt>
              <dd>0.84</dd>
            </div>
          </dl>
          <p className="hero-footnote">
            Estimates are generated by a Random Forest model and are a
            starting point for negotiation — not a formal appraisal.
          </p>
        </div>
      </section>

      <section className="form-panel">
        <div className="form-panel__header">
          <span className="eyebrow">Property particulars</span>
          <h2>Describe the property</h2>
        </div>
        {error && (
          <div className="alert alert--error" role="alert">
            {error}
          </div>
        )}
        <PredictionForm onSubmit={handleSubmit} submitting={submitting} />
      </section>
    </div>
  );
}
